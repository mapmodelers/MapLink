"""MapLink force-save (one .blend) — runs in a headless Blender subprocess.

Invoked by MAPLINK_OT_ForceSaveAll for each referenced .blend, and (v1.14)
by MAPLINK_OT_BatchStandardize for each in-scope project .blend.  Performs:

    1. Enables the MapLink addon (so save_pre/save_post handlers register).
    2. Disables fbx_export_on_save's save_post — we run FBX export inline
       rather than spawning a nested subprocess.
    3. Opens the target .blend.
    4. Calls bpy.ops.wm.save_mainfile() — this fires:
         - nav_drill._on_save_pre   → auto P4 checkout of the .blend
         - sidecar_analysis._on_save_post → writes <stem>_analysis.json
                                            + <stem>_filehash.txt and P4-adds them
    5. Runs the MapLink UE plugin's maplink_export.py main() inline with
       --mode both --lock — produces the plugin-cache analysis.json,
       filehash.txt, and Export/<stem>/<stem>.fbx (v1.13: under the
       artifact root — <UEProject>/Saved/MapLink — not the plugin dir).

Invocation (built by the orchestrator operator):

    <blender.exe> --background <blend>
        --python <addon>/maplink_force_save.py --
        --blend         <blend>
        --plugin-dir    <plugin>
        --addon-package <addon python package name>

v1.14 — Batch Standardize additions:
    --standardize vc,uv,outliner,collections   apply the ticked current-file
        standardization actions after opening (LI_/SM_ stems only — BP_ and
        unprefixed .blends are never mutated by standardize actions).
    --skip-unchanged   when set, files no standardize action changed are NOT
        checked out / saved / exported — the worker exits with rc 7 ("skip").
        Ticking "Force re-save" in the UI simply omits this flag, so every
        in-scope file goes through the full save pipeline and its sidecars
        (<stem>_analysis.json / <stem>_filehash.txt) are regenerated by the
        normal export-on-save path.
    --cl <n> / --cl-desc "<desc>"   route the .blend checkout into a specific
        pending changelist (pre-created once by the orchestrator so parallel
        workers can't race a create).  Sidecar adds follow the .blend's CL
        automatically (sidecar_analysis uses find_file_changelist).

Does NOT pass --factory-startup — user prefs must load so the addon is
available for enable.  Output is captured by the orchestrator to a log file.

Exit codes: 0 = saved, 7 = skipped (unchanged), anything else = failure.
"""

import argparse
import importlib
import importlib.util
import os
import stat
import sys

import bpy
import addon_utils


def _parse_args():
    argv = sys.argv
    if '--' in argv:
        argv = argv[argv.index('--') + 1:]
    else:
        argv = []
    ap = argparse.ArgumentParser(description="MapLink force-save (single .blend)")
    ap.add_argument('--blend',         required=True)
    ap.add_argument('--plugin-dir',    default='',
                    help="UE plugin dir (Scripts/maplink_export.py).  May be "
                         "empty for standalone artists — the inline FBX "
                         "export is then skipped (sidecars still regenerate "
                         "via the save_post handler).")
    ap.add_argument('--artifact-root', default='',
                    help="v1.13: root for generated Logs/Export artifacts "
                         "(defaults to --plugin-dir, legacy layout)")
    ap.add_argument('--addon-package', required=True,
                    help="Python package name of the MapLink_Blender addon "
                         "(e.g. MapLink_BlenderV1_4_1)")
    ap.add_argument('--no-p4', action='store_true',
                    help="Disable P4 operations (best-effort already, but force off).")
    # v1.14 — Batch Standardize
    ap.add_argument('--standardize', default='',
                    help="Comma list of standardize actions to apply after "
                         "open: vc,uv,outliner,collections (LI_/SM_ only).")
    ap.add_argument('--skip-unchanged', action='store_true',
                    help="Skip checkout/save/export when no standardize "
                         "action changed the file (exit code 7).")
    ap.add_argument('--cl', type=int, default=0,
                    help="Pending changelist number for the .blend checkout "
                         "(pre-created by the orchestrator).")
    ap.add_argument('--cl-desc', default="[MapLink] Force-Save All",
                    help="Changelist description used when --cl is not given.")
    ap.add_argument('--dry-run', action='store_true',
                    help="Report only: apply standardize actions in memory "
                         "to measure impact, but NEVER checkout/save/export. "
                         "Exit 9 = would change/save, 7 = would skip.")
    return ap.parse_args(argv)


# v1.14 — standardize actions only ever mutate LI_/SM_ content; BP_ proxy
# .blends can disturb the Blueprint they are linked to, unprefixed .blends
# are not MapLink assets.  (Force re-save still saves them — saving without
# actions is content-neutral.)
_STANDARDIZE_PREFIXES = ("LI_", "SM_")


def _apply_standardize(pkg: str, blend_path: str, actions):
    """Apply the requested standardize actions to the open scene.
    Returns (changed: bool, summary: str)."""
    stem = os.path.splitext(os.path.basename(blend_path))[0]
    if not stem.startswith(_STANDARDIZE_PREFIXES):
        return False, "standardize n/a (not LI_/SM_)"

    scene = bpy.context.scene
    if scene is None:
        return False, "no scene"

    mt = importlib.import_module(f"{pkg}.modeling_tools")
    oc = importlib.import_module(f"{pkg}.outliner_cleanup")

    changed = False
    parts = []
    if 'vc' in actions:
        c = mt.standardize_scene_vc(scene)
        changed |= (c['create'] + c['standardize']) > 0
        parts.append(f"VC {c['create']}+{c['standardize']}/{c['total']}")
    if 'uv' in actions:
        c = mt.standardize_scene_uv(scene)
        changed |= c['renamed'] > 0
        parts.append(f"UV {c['renamed']}/{c['total']} "
                     f"({c['nodes']} node ref(s))")
    if 'outliner' in actions:
        res = oc.run_cleanup(scene)
        if res is not None:
            _msg, n_obj, n_mesh = res
            changed |= (n_obj + n_mesh) > 0
            parts.append(f"outliner {n_obj}obj/{n_mesh}mesh")
    if 'collections' in actions:
        res = oc.run_collection_cleanup(scene, None)  # colour map from prefs
        if res is not None:
            _msg, n_moved = res
            changed |= n_moved > 0
            parts.append(f"collections {n_moved} moved")
    return changed, ", ".join(parts) if parts else "no actions"


def _enable_addon(pkg: str):
    """Enable the addon non-persistently.  Returns True on success."""
    try:
        # default_set=False: don't persist into user prefs (this is a one-shot
        # headless run).  persistent=False: don't write to disk.
        ok = addon_utils.enable(pkg, default_set=False, persistent=False)
        return ok is not None
    except Exception as exc:
        print(f"[force-save] addon_utils.enable failed: {exc}")
        return False


def _disable_fbx_save_post(pkg: str):
    """Remove the FBX-spawn save_post handler so we don't launch a nested
    subprocess on save (we'll do the export inline)."""
    try:
        mod = importlib.import_module(f"{pkg}.fbx_export_on_save")
        mod.unregister()
        print(f"[force-save] Disabled {pkg}.fbx_export_on_save save_post handler.")
    except Exception as exc:
        print(f"[force-save] WARN: could not disable fbx_export_on_save: {exc}")


def _run_inline_export(blend_path: str, plugin_dir: str, artifact_root: str):
    """Import maplink_export.py from the UE plugin's Scripts dir and call
    main() with the same args UE / save_post would use, but inline (no
    subprocess)."""
    script_path = os.path.join(plugin_dir, 'Scripts', 'maplink_export.py')
    if not os.path.isfile(script_path):
        print(f"[force-save] ERROR: maplink_export.py not found at {script_path}")
        return 1

    spec = importlib.util.spec_from_file_location("maplink_export", script_path)
    if spec is None or spec.loader is None:
        print(f"[force-save] ERROR: could not load spec for {script_path}")
        return 1
    me = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(me)

    old_argv = sys.argv[:]
    # Format expected by maplink_export._parse_args: everything after '--'.
    sys.argv = ['blender', '--',
                '--mode',   'both',
                '--blend',  blend_path,
                '--outdir', artifact_root or plugin_dir,
                '--lock']
    try:
        me.main()
        return 0
    except SystemExit as se:
        return int(se.code) if se.code is not None else 0
    except Exception as exc:
        print(f"[force-save] ERROR: maplink_export.main() raised: {exc}")
        import traceback
        traceback.print_exc()
        return 1
    finally:
        sys.argv = old_argv


def main():
    opts = _parse_args()
    print(f"[force-save] === {opts.blend} ===")

    if not os.path.isfile(opts.blend):
        print(f"[force-save] ERROR: blend not found: {opts.blend}")
        return 2

    # 1. Enable addon (so save_pre/save_post handlers register).
    if not _enable_addon(opts.addon_package):
        print(f"[force-save] ERROR: failed to enable addon '{opts.addon_package}'")
        return 3

    # 2. Disable the FBX-spawn handler — we'll run export inline.
    _disable_fbx_save_post(opts.addon_package)

    # 3. Open the .blend.  open_mainfile triggers load_post handlers but not
    #    save_post.  Note that the Blender command-line already opened the
    #    .blend if it was passed as a positional arg — calling open_mainfile
    #    again is harmless and ensures a known state.
    try:
        bpy.ops.wm.open_mainfile(filepath=opts.blend)
    except Exception as exc:
        print(f"[force-save] ERROR: open_mainfile failed: {exc}")
        return 4

    # 3a. v1.14 — apply the ticked standardize actions (LI_/SM_ only), and
    #     honour --skip-unchanged: an untouched file is left completely alone
    #     (no checkout, no save, no export) and reports rc 7 to the
    #     orchestrator's skip column.
    actions = [a.strip() for a in (opts.standardize or '').split(',')
               if a.strip()]
    if actions:
        try:
            changed, summary = _apply_standardize(
                opts.addon_package, opts.blend, actions)
        except Exception as exc:
            import traceback
            traceback.print_exc()
            print(f"[force-save] ERROR: standardize failed: {exc}")
            return 8
        print(f"[force-save] standardize [{','.join(actions)}]: {summary} "
              f"-> {'CHANGED' if changed else 'unchanged'}")
        if opts.dry_run:
            # In-memory only — the subprocess exits without saving, so the
            # applied actions are discarded.  9 = would change (or would be
            # force re-saved), 7 = would skip.
            would = changed or not opts.skip_unchanged
            print(f"[force-save] DRY RUN: "
                  f"{'WOULD SAVE' if would else 'would skip'}: {opts.blend}")
            return 9 if would else 7
        if opts.skip_unchanged and not changed:
            print(f"[force-save] SKIP (unchanged): {opts.blend}")
            return 7
    elif opts.dry_run:
        # No actions ticked: only Force re-save could touch this file.
        would = not opts.skip_unchanged
        print(f"[force-save] DRY RUN: "
              f"{'WOULD SAVE (force re-save)' if would else 'would skip'}: "
              f"{opts.blend}")
        return 9 if would else 7
    elif opts.skip_unchanged:
        # No actions ticked and no force re-save — nothing to do.
        print(f"[force-save] SKIP (no actions): {opts.blend}")
        return 7

    # 3b. v1.4.3 — Belt-and-suspenders: try P4 edit, then strip Windows
    #     read-only bit if needed.  Covers files not in P4, p4 missing
    #     from PATH, exclusive-lock edge cases, etc.
    #     v1.14 — --cl routes the checkout into the orchestrator's pending
    #     batch CL; sidecar adds follow the .blend's CL automatically.
    p4_ok = False
    p4_msg = ""
    if not opts.no_p4:
        try:
            p4_mod = importlib.import_module(f"{opts.addon_package}.p4_integration")
            if p4_mod.p4_available():
                if opts.cl and opts.cl > 0:
                    p4_ok, p4_msg = p4_mod.checkout_or_add(
                        opts.blend, cl=opts.cl)
                else:
                    p4_ok, p4_msg = p4_mod.checkout_file(
                        opts.blend, description=opts.cl_desc)
                print(f"[force-save] P4 checkout {'OK' if p4_ok else 'WARN'}: "
                      f"{p4_msg}")
            else:
                p4_msg = "p4 not on PATH"
                print(f"[force-save] P4 not available — skipping checkout")
        except Exception as exc:
            p4_msg = str(exc)
            print(f"[force-save] P4 checkout error (non-fatal): {exc}")

    try:
        if os.path.isfile(opts.blend) and not os.access(opts.blend, os.W_OK):
            os.chmod(opts.blend, os.stat(opts.blend).st_mode | stat.S_IWRITE)
            print(f"[force-save] chmod +w applied (P4 status: "
                  f"{'OK' if p4_ok else 'bypassed: ' + (p4_msg or 'unknown')})")
    except OSError as exc:
        print(f"[force-save] chmod failed: {exc}")

    # 4. Save — fires nav_drill._on_save_pre (no-op outside drill) and
    #    sidecar_analysis._on_save_post (sidecar write + P4 add).
    try:
        bpy.ops.wm.save_mainfile()
    except Exception as exc:
        print(f"[force-save] ERROR: save_mainfile failed: {exc}")
        return 5

    # 5. Inline export (analyse + FBX + plugin-cache filehash + .export.lock).
    #    v1.14 — gated: unprefixed .blends have no MapLink export, and a
    #    standalone artist without a configured UE plugin dir still gets the
    #    save + sidecar regen above (export-on-save handles FBX next time).
    stem = os.path.splitext(os.path.basename(opts.blend))[0]
    if not stem.startswith(("BP_", "LI_", "SM_")):
        print(f"[force-save] inline export skipped (not a MapLink-prefixed "
              f"stem): {stem}")
    elif not opts.plugin_dir or not os.path.isdir(opts.plugin_dir):
        print("[force-save] inline export skipped (no UE plugin dir "
              "configured — standalone mode)")
    else:
        rc = _run_inline_export(opts.blend, opts.plugin_dir, opts.artifact_root)
        if rc != 0:
            print(f"[force-save] WARN: inline export returned {rc}")
            return 6

    print(f"[force-save] OK: {opts.blend}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
